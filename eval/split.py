"""Builds the eval set for the AAPL 10-Q filing and splits it into dev/test.

Two sources get merged: the 2 questions from the upstream qna_data.csv that
are actually answerable from this one filing, plus a set of additional
questions drafted for this document (see build_single_doc_questions.py) and
hand-reviewed before being trusted.

Usage:
    python -m eval.split
"""

from __future__ import annotations

import hashlib
import random
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
DOC_ID = "2022 Q3 AAPL"

RAW_QNA_CSV = REPO_ROOT / "data" / "raw" / "aapl" / "qna_data.csv"
SUPPLEMENTAL_CSV = REPO_ROOT / "data" / "eval" / f"{DOC_ID}_supplemental_draft.csv"
EVAL_CSV = REPO_ROOT / "data" / "eval" / "aapl_eval.csv"
DEV_CSV = REPO_ROOT / "data" / "eval" / "aapl_dev.csv"
TEST_CSV = REPO_ROOT / "data" / "eval" / "aapl_test.csv"

SEED = 42
TEST_FRACTION = 8 / 26

COLUMNS = ["Question", "Source Docs", "Question Type", "Source Chunk Type", "Answer"]


def build_eval_set() -> pd.DataFrame:
    gold = pd.read_csv(RAW_QNA_CSV)
    gold = gold[gold["Source Docs"] == f"*{DOC_ID}*"][COLUMNS]

    drafted = pd.read_csv(SUPPLEMENTAL_CSV, encoding="utf-8")
    # one drafted question duplicated a gold question almost word for word
    drafted = drafted[~drafted["Question"].str.contains("Cash generated by operating activities", na=False)]
    drafted["Question Type"] = drafted["Question Type"].replace(
        {"Single-Doc Single-Chunk": "Single-Doc Single-Chunk RAG", "Single-Doc Multi-Chunk": "Single-Doc Multi-Chunk RAG"}
    )

    merged = pd.concat([gold, drafted[COLUMNS]], ignore_index=True)
    merged["doc_ids"] = DOC_ID
    return merged


def stratified_split(df: pd.DataFrame, seed: int, test_fraction: float) -> tuple[pd.DataFrame, pd.DataFrame]:
    df = df.copy()
    df["_stratum"] = df["Question Type"] + "|" + df["Source Chunk Type"]

    dev_indices: list[int] = []
    test_indices: list[int] = []

    for stratum in sorted(df["_stratum"].unique()):
        group_idx = df.index[df["_stratum"] == stratum].tolist()
        stratum_seed = int(hashlib.sha256(f"{seed}:{stratum}".encode()).hexdigest(), 16) % (2**32)
        random.Random(stratum_seed).shuffle(group_idx)
        n_test = round(len(group_idx) * test_fraction)
        test_indices.extend(group_idx[:n_test])
        dev_indices.extend(group_idx[n_test:])

    dev_df = df.loc[dev_indices].drop(columns=["_stratum"]).reset_index(drop=True)
    test_df = df.loc[test_indices].drop(columns=["_stratum"]).reset_index(drop=True)
    return dev_df, test_df


def main() -> None:
    merged = build_eval_set()
    merged.to_csv(EVAL_CSV, index=False)

    dev_df, test_df = stratified_split(merged, seed=SEED, test_fraction=TEST_FRACTION)
    dev_df.to_csv(DEV_CSV, index=False)
    test_df.to_csv(TEST_CSV, index=False)

    print(f"eval set: {len(merged)} questions -> {EVAL_CSV}")
    print(f"dev:  {len(dev_df)} rows -> {DEV_CSV}")
    print(f"test: {len(test_df)} rows -> {TEST_CSV}")


if __name__ == "__main__":
    main()
